"""Emit the false-multiples table for the paper's appendix.

Reads `name_property_dissociation.false_multiples.by_shared` written by analyze_inventive_multiples.py
and lays it out exactly like the tau table (tab_tau_multiples.tex): one row per shared-property count
among same-name pairs (two models, same anchors, same coined name after normalisation) -- the 0 row is
the false multiples -- with (a) count, share of same-name pairs and share of inventions, (b) the same
share split by task, (c) split by whether the two models come from the same provider family.

Float-less fragment, NO caption and NO label (captions are the author's, in the section file).

    .venv/bin/python -m src.kg_creat.scripts.make_false_multiples_table \\
        data/kg_creat/kombine_test30/analysis/inventive_multiples.json \\
        papers/kg_creat-iclr/media/tab_false_multiples.tex
"""
import argparse
import json
from pathlib import Path

HEADER = "% Auto-generated by make_false_multiples_table.py -- do not edit by hand."
ROWS = [("blending", "Blending"), ("analogy", "Analogy"), ("all", "All")]


def ratio(num, den):
    if den is None or den <= 0 or den != den:
        return "--"
    return f"{num / den:.1f}$\\times$"


def render(d) -> str:
    """Same layout as the tau table: rows by shared-property count among same-name pairs, the first row
    (0 shared) being the false multiples; (a) counts, (b) by task, (c) by model family."""
    fm = d["name_property_dissociation"]["false_multiples"]
    L = [HEADER,
         "% Fragment (no float wrapper, no caption): \\input inside a table float; the caption and label",
         "% live in the section file next to the \\input.",
         r"\footnotesize",
         r"\setlength{\tabcolsep}{3pt}",
         r"\begin{tabular}{cccccccccc}",
         r"\toprule",
         r" & \multicolumn{3}{c}{\textbf{(a) Same-name pairs}} & \multicolumn{3}{c}{\textbf{(b) \% of same-name pairs, by task}} & "
         r"\multicolumn{3}{c}{\textbf{(c) \% of same-name pairs, by model family}} \\",
         r"\cmidrule(lr){2-4}\cmidrule(lr){5-7}\cmidrule(lr){8-10}",
         r"$\tau$ & Count & \% of pairs & \% of inventions & Blend & Analogy & Blend/Analogy & Same & Different & Same/Diff \\",
         r"\midrule"]
    for r in fm["by_shared"]:
        label = "0 (false)" if r["shared"] == 0 else ("$\\ge 3$" if r["shared"] == 3 else str(r["shared"]))
        L.append(f"{label} & {r['n']:,} & {r['pct_of_same_name_pairs']:.1f}\\% & {r['inventions_pct']:.1f}\\% & "
                 f"{r['blending_pct']:.1f}\\% & {r['analogy_pct']:.1f}\\% & {ratio(r['blending_pct'], r['analogy_pct'])} & "
                 f"{r['same_provider_pct']:.1f}\\% & {r['cross_provider_pct']:.1f}\\% & {ratio(r['same_provider_pct'], r['cross_provider_pct'])} \\\\")
    L += [r"\bottomrule", r"\end{tabular}", ""]
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("src", type=Path)
    ap.add_argument("dst", type=Path)
    a = ap.parse_args()
    d = json.loads(a.src.read_text())
    if "false_multiples" not in d.get("name_property_dissociation", {}):
        raise SystemExit(f"{a.src} has no false_multiples block -- re-run analyze_inventive_multiples.py")
    a.dst.write_text(render(d))
    print(f"wrote {a.dst}")


if __name__ == "__main__":
    main()
