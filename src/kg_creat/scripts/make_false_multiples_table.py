"""Emit the false-multiples table for the paper's appendix.

Reads `name_property_dissociation.false_multiples` written by analyze_inventive_multiples.py: for each
task and overall, the number of same-name pairs (two models, same anchors, same coined name after
normalisation), how many of them share no property at theta (false multiples), how the rest split by
shared-property count, and how many inventions belong to at least one false multiple.

Float-less fragment, NO caption and NO label (captions are the author's, in the section file).

    .venv/bin/python -m src.kg_creat.scripts.make_false_multiples_table \\
        data/kg_creat/kombine_test30/analysis/inventive_multiples.json \\
        papers/kg_creat-iclr/media/tab_false_multiples.tex
"""
import argparse
import json
from pathlib import Path

HEADER = "% Auto-generated by make_false_multiples_table.py -- do not edit by hand."
ROWS = [("blending", "Blending"), ("analogy", "Analogy"), ("all", "All")]


def render(d) -> str:
    fm = d["name_property_dissociation"]["false_multiples"]
    L = [HEADER,
         "% Fragment (no float wrapper, no caption): \\input inside a table float; the caption and label",
         "% live in the section file next to the \\input.",
         r"\scriptsize",
         r"\setlength{\tabcolsep}{4pt}",
         r"\begin{tabular}{@{}l rr r rrr rr r@{}}",
         r"\toprule",
         r" & \multicolumn{3}{c}{Same-name pairs} & \multicolumn{3}{c}{Pairs sharing $\tau$ properties} & \multicolumn{3}{c}{Inventions} \\",
         r"\cmidrule(lr){2-4}\cmidrule(lr){5-7}\cmidrule(lr){8-10}",
         r"Task & Count & False multiples & \% false & $\tau=1$ & $\tau=2$ & $\tau\ge3$ & Total & In a false multiple & \% of inventions \\",
         r"\midrule"]
    for key, label in ROWS:
        b = fm[key]; sc = b["shared_counts"]
        t1 = int(sc.get("1", 0)); t2 = int(sc.get("2", 0)); t3 = sum(v for k, v in sc.items() if int(k) >= 3)
        L.append(f"{label} & {b['same_name_pairs']:,} & {b['false_multiples']:,} & {b['pct_of_same_name_pairs']:.1f}\\% & {t1} & {t2} & {t3} "
                 f"& {b['n_inventions']:,} & {b['inventions_false_multiple']:,} & {b['pct_inventions_false_multiple']:.1f}\\% \\\\")
    L += [r"\bottomrule", r"\end{tabular}", ""]
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("src", type=Path)
    ap.add_argument("dst", type=Path)
    a = ap.parse_args()
    d = json.loads(a.src.read_text())
    if "false_multiples" not in d.get("name_property_dissociation", {}):
        raise SystemExit(f"{a.src} has no false_multiples block -- re-run analyze_inventive_multiples.py")
    a.dst.write_text(render(d))
    print(f"wrote {a.dst}")


if __name__ == "__main__":
    main()
