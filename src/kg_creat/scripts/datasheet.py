"""Emit a datasheet for a Regime-A scoring run: exactly what was measured, on what, at what n.

A finding is only interpretable alongside its sample. This computes — from the actual scored data,
never hand-transcribed — the dataset dimensions, the sampling frame (including how narrow the
realized endpoint pool is), the relation-class derivation, and the per-finding n's the report cites,
and writes them as a markdown datasheet the report links to. Re-run it whenever the data changes so
the numbers can never drift from the prose.

    .venv/bin/python src/kg_creat/scripts/datasheet.py \
        --scores data/kg_creat/scores_regimeA_all \
        --prompts data/kg_creat/prompts_regimeA_pass2 \
        --gc data/kg_creat/gc_domains_v1 \
        --out docs/reports/2026-07-22_kg_creat_creativity/datasheet.md
"""

import argparse
import json
import math
from collections import Counter
from pathlib import Path
from statistics import mean

REPORTED = ["baseline", "categorical", "exclusion", "inclusion_rare", "inclusion"]
JUDGE = "openai/gpt-oss-120b"


def _ok(x):
    return x is not None and not (isinstance(x, float) and math.isnan(x))


def load(scores_dir):
    A = Path(scores_dir)
    return {d.name: json.loads((d / "path_scores.json").read_text())
            for d in sorted(A.iterdir()) if (d / "path_scores.json").exists()}


def dataset_facts(recs_by_model, prompts_dir, gc_dir):
    models = sorted(recs_by_model)
    one = recs_by_model[models[0]]
    bundles = sorted({r["bundle_id"] for r in one})
    cells = sorted({r["mode"] for r in one})

    specs = json.loads((Path(prompts_dir) / "prompts.json").read_text())
    per_bundle = [s for s in specs if s["mode"] == "exclusion"]
    ent = Counter()
    for s in per_bundle:
        ent[s["u_label"]] += 1
        ent[s["v_label"]] += 1

    # realized-endpoint domain mix (the generality-critical fact), if the G_c metadata is present
    dom = Counter()
    gc_dir = Path(gc_dir)
    if (gc_dir / "gc.json").exists() and (gc_dir / "entity_domains.json").exists():
        gc = json.loads((gc_dir / "gc.json").read_text())
        ed = json.loads((gc_dir / "entity_domains.json").read_text())
        lab2qid = {n["label"]: n["id"] for n in gc["nodes"]}
        for e in ent:
            d = ed.get(lab2qid.get(e, ""))
            if d:
                dom[d] += 1

    per_cell = {}
    for c in REPORTED:
        paths = [r for recs in recs_by_model.values() for r in recs if r["mode"] == c]
        per_cell[c] = {
            "prompts_per_model": len({r["prompt_id"] for r in one if r["mode"] == c}),
            "paths_total": len(paths),
            "well_formed": sum(1 for r in paths if r.get("well_formed")),
            "sat_determined": sum(1 for r in paths if r.get("sat") is not None),
        }
    return {"models": models, "bundles": bundles, "cells": cells, "endpoints": ent,
            "endpoint_domains": dom, "per_cell": per_cell}


def relation_classes(prompts_dir):
    ct = json.loads((Path(prompts_dir) / "classes_targets.json").read_text())
    return ct["classes"]


def finding_ns(recs_by_model):
    """The n behind each statistic the report reports, computed the same way the report computes it."""
    S = {}  # per-model per-cell summary rebuilt from path scores for R_emit / paired counts
    out = {}
    constraints = [c for c in REPORTED if c != "baseline"]

    # (a) the net-effect boxplot + significance: one paired effect per model
    out["net_effect_unit"] = f"{len(recs_by_model)} model-level paired effects per constraint"

    # (b) R_emit (novelty over ALL emitted paths, no selection)
    def rmean(recs, mode):
        v = [r["R"] for r in recs if r["mode"] == mode and _ok(r["R"])]
        return (mean(v), len(v)) if v else (None, 0)
    remit = {}
    for c in REPORTED:
        ns = [rmean(recs, c)[1] for recs in recs_by_model.values()]
        remit[c] = sum(ns)
    out["R_emit_paths"] = remit

    # (c) within-bundle paired R_valid: count paired (model,bundle) cells
    paired = {}
    for c in constraints:
        n = 0
        for recs in recs_by_model.values():
            by = {}
            for r in recs:
                if r["sat"] and _ok(r["R"]):
                    by.setdefault((r["bundle_id"], r["mode"]), []).append(r["R"])
            for b in {k[0] for k in by}:
                if (b, "baseline") in by and (b, c) in by:
                    n += 1
        paired[c] = n
    out["within_bundle_paired"] = paired
    return out


def render(facts, classes, ns):
    L = []
    L.append("# Regime-A datasheet (auto-generated)\n")
    L.append("Generated by `src/kg_creat/scripts/datasheet.py` from the scored data. Do not edit by "
             "hand; re-run when the data changes. Every finding in the report should cite the "
             "relevant row here.\n")

    L.append("## Models (n = %d)\n" % len(facts["models"]))
    L.append("A convenience sample spanning four developer families and a cheap→frontier capability "
             "range; **not** a random or exhaustive sample of models.\n")
    for m in facts["models"]:
        L.append(f"- `{m}`")
    L.append("")

    L.append("## Task and cells\n")
    pc = facts["per_cell"]
    L.append("Reported constraint set: **4 types + baseline** (ordering piloted and dropped — see "
             "assessment.md §7c). Each prompt requests `k = 5` paths `u → v`.\n")
    L.append("| cell | prompts/model | paths (all models) | well-formed | sat-determined |")
    L.append("|---|---|---|---|---|")
    for c in REPORTED:
        r = pc[c]
        L.append(f"| {c} | {r['prompts_per_model']} | {r['paths_total']} | {r['well_formed']} | "
                 f"{r['sat_determined']} |")
    tot = sum(r["paths_total"] for r in pc.values())
    L.append(f"\n**Total paths in the reported set: {tot}** (excludes the dropped ordering cell). "
             f"Judge: `{JUDGE}`.\n")

    L.append("## Sampling frame — endpoints (the generality-critical part)\n")
    ep = facts["endpoints"]
    L.append(f"The {len(facts['bundles'])} endpoint bundles are drawn from only **{len(ep)} distinct "
             f"entities**, and are heavily concentrated:\n")
    for e, n in ep.most_common(10):
        L.append(f"- {e} — in {n} of {len(facts['bundles'])} bundles")
    if facts["endpoint_domains"]:
        L.append("\nDomain of those distinct endpoint entities (Wikidata, via the G_c domain tags):\n")
        for d, n in facts["endpoint_domains"].most_common():
            L.append(f"- {d}: {n}")
    L.append("\n**Scope caveat.** The G_c seeds were domain-diverse (22 anchors across 13 domains), "
             "but the matched-bundle sampler keeps only endpoints that are highly connected "
             "(`min_degree ≥ 4`, `≥ 6` multi-hop routes) and on which `≥ 3` constraint types both "
             "bite and remain satisfiable. Those filters select hub entities, so the realized pool "
             "collapsed onto prominent geopolitical entities (countries + international "
             "organizations). Findings below are established **for paths among well-connected "
             "real-world entities of this kind**; they are *not* evidence about sparse or "
             "domain-specific subgraphs, nor about entities with few multi-hop routes.\n")

    L.append("## Constraint targets\n")
    L.append("Relation-class constraints are defined over **8 classes** derived by k-means over "
             "embeddings of the top-150 relations models actually emitted in the baseline pass; "
             "per-bundle targets are chosen against each bundle's own baseline behaviour so each "
             "constraint bites by construction. Class shares in the baseline corpus:\n")
    for c in classes:
        L.append(f"- {c['name']}: {c['share']*100:.1f}% ({len(c['members'])} member relations)")
    L.append("")

    L.append("## n behind each finding\n")
    L.append(f"- **Net creativity effect + significance:** {ns['net_effect_unit']} "
             "(one-sample t-test on the 8 values, Holm-corrected). The 8 models are the "
             "replication unit — *not* the ~240 per-bundle differences.")
    L.append("- **Novelty gain is causal (R_emit, all emitted paths, no success filtering):** "
             + ", ".join(f"{c} n={ns['R_emit_paths'][c]}" for c in REPORTED if c != "baseline")
             + f" (baseline n={ns['R_emit_paths']['baseline']}).")
    L.append("- **Within-bundle paired novelty of successes (ΔR_valid):** "
             + ", ".join(f"{c} n={ns['within_bundle_paired'][c]}" for c in ns['within_bundle_paired'])
             + " paired (model,bundle) cells where the model succeeded under both baseline and the "
             "constraint.")
    L.append("- **Failure-channel decomposition:** over the well-formed, sat-determined paths per "
             "cell in the table above.")
    L.append("")
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--scores", default="data/kg_creat/scores_regimeA_all")
    ap.add_argument("--prompts", default="data/kg_creat/prompts_regimeA_pass2")
    ap.add_argument("--gc", default="data/kg_creat/gc_domains_v1")
    ap.add_argument("--out", default=None)
    a = ap.parse_args()
    recs = load(a.scores)
    facts = dataset_facts(recs, a.prompts, a.gc)
    classes = relation_classes(a.prompts)
    ns = finding_ns(recs)
    md = render(facts, classes, ns)
    if a.out:
        Path(a.out).write_text(md)
        print(f"wrote {a.out}")
    else:
        print(md)


if __name__ == "__main__":
    main()
