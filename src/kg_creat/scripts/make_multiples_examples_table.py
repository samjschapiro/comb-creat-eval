"""Emit the paper's inventive-multiples showcase as two side-by-side LaTeX tables.

Each table is one tau-multiple from the `multiples` block of inventive_multiples.json: the two
models (logo + name), their coined names, then one row per matched property pair with the cosine
in the middle column, then the unmatched properties of each side in grey. The pairs shown are the
same explicit choice as the figure script (plot_multiples_examples.PANELS / PAPER_PANELS), so the
two never disagree.

A second fragment, tab_same_name_examples.tex (appendix; or a second row of the main fragment with
--same-name-row), shows the converse (Finding: naming
and inventing dissociate): two inventions that carry the SAME coined name but share no property. Their
rows are the best one-to-one pairing of properties (Hungarian assignment on cosine), unshaded, so the
reader sees that even the closest pairs fall well below theta. These come from the
`name_property_dissociation` examples in the same JSON.

Both outputs are float-less fragments meant to be \\input inside a table float. They carry NO caption
and NO label: captions belong to the author and live in the section file next to the \\input, so
regenerating these files can never overwrite one.

    .venv_mlx/bin/python -m src.kg_creat.scripts.make_multiples_examples_table \\
        data/kg_creat/kombine_test30/analysis/inventive_multiples.json \\
        papers/kg_creat-iclr/media/tab_multiples_examples.tex
"""
import argparse
import json
from pathlib import Path

import numpy as np
from scipy.optimize import linear_sum_assignment

from src.kg_creat.model_names import DISPLAY, LOGO_SLUG, _provider
from src.kg_creat.scripts.plot_multiples_examples import PAPER_PANELS, find

# (task, u, v, model a, model b): same-name pairs for the second row, looked up in the JSON's
# name_property_dissociation examples; each must be present or the script fails.
SAME_NAME_PANELS = [   # everyday anchors, common-sense properties, and almost nothing in common
    ("blending", "The blue whale", "The mattress", "anthropic_claude-fable-5", "qwen_qwen-2-5-72b-instruct"),   # "whale bed"
    ("blending", "Rice", "Radio", "moonshotai_kimi-k2", "openai_gpt-4o-mini"),                                   # "rice radio"
]
RUN = Path("data/kg_creat/kombine_test30")

HEADER = "% Auto-generated by make_multiples_examples_table.py -- do not edit by hand."
THETA = 0.674          # the property-match bar: a cosine at theta gets the lightest tint
MIN_TINT, MAX_TINT = 14, 55   # percent of the row colour mixed into white, at theta and at cosine 1.0


def tex(s: str) -> str:
    return (s.replace("\\", r"\textbackslash{}").replace("&", r"\&").replace("%", r"\%")
             .replace("_", r"\_").replace("#", r"\#").replace("$", r"\$"))


def model_cell(key: str) -> str:
    slug = LOGO_SLUG.get(_provider(key))
    logo = f"\\provlogo{{{slug}}}" if slug else ""
    return f"{logo}{tex(DISPLAY.get(key, key.split('_', 1)[-1]))}"


def one_table(m, letter, shade=True, kind="Inventive Multiple", number=1) -> str:
    """kind/number head the panel title, e.g. "(a) Inventive Multiple #1: \\emph{Opera} + \\emph{Documentary film}"
    (the author's wording on Overleaf, 2026-09-14); a same-name pair is a "False Multiple"."""
    a, b = m["a"], m["b"]
    matched = sorted(m["matches"], key=lambda x: -x["cos"])
    ma, mb = {x["a"] for x in matched}, {x["b"] for x in matched}
    # properties keep their index in the invention's own list (P = {p_1..p_k}, P' = {p'_1..p'_k'}),
    # so a matched row shows WHICH property paired with which, not a positional alignment
    pa = lambda i: f"$p_{{{i + 1}}}$: {tex(a['properties'][i])}"
    pb = lambda j: f"$p'_{{{j + 1}}}$: {tex(b['properties'][j])}"
    rest_a = [i for i in range(len(a["properties"])) if i not in ma]
    rest_b = [j for j in range(len(b["properties"])) if j not in mb]
    op = "+" if m["task"] == "blending" else "::"
    L = [f"\\begin{{minipage}}[t]{{0.49\\linewidth}}\\centering",
         f"\\textbf{{({letter}) {kind} \\#{number}: \\emph{{{tex(m['u'])}}} {op} \\emph{{{tex(m['v'])}}}}}\\\\[3pt]",
         r"\begin{tabular}{@{}>{\raggedright\arraybackslash}p{0.43\linewidth}@{\hspace{4pt}}c@{\hspace{4pt}}"
         r">{\raggedright\arraybackslash}p{0.43\linewidth}@{}}",
         r"\toprule",
         f"{model_cell(a['model'])} & & {model_cell(b['model'])} \\\\",
         f"\\textbf{{``{tex(a['name'])}''}} & {{\\scriptsize cos}} & \\textbf{{``{tex(b['name'])}''}} \\\\",
         r"\midrule"]
    # matched rows are shaded in the task colour in proportion to the cosine, heatmap-style: theta maps to the
    # lightest tint and 1.0 to the darkest, so the reader sees how tight each match is at a glance.
    # Unmatched rows are unshaded.
    for x in matched:
        if not shade:                                  # a same-name pair: best pairing shown, nothing reaches theta
            L.append(f"{pa(x['a'])} & \\textcolor{{gray}}{{${x['cos']:.2f}$}} & {pb(x['b'])} \\\\")
            continue
        t = max(0.0, min(1.0, (x["cos"] - THETA) / (1.0 - THETA)))
        pct = int(round(MIN_TINT + (MAX_TINT - MIN_TINT) * t))
        L.append(f"\\rowcolor{{multRow!{pct}}} {pa(x['a'])} & ${x['cos']:.2f}$ & {pb(x['b'])} \\\\")
    if rest_a or rest_b:
        L.append(r"\midrule")
        for k in range(max(len(rest_a), len(rest_b))):
            ra = f"\\textcolor{{gray}}{{{pa(rest_a[k])}}}" if k < len(rest_a) else ""
            rb = f"\\textcolor{{gray}}{{{pb(rest_b[k])}}}" if k < len(rest_b) else ""
            L.append(f"{ra} & & {rb} \\\\")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{minipage}"]
    return "\n".join(L)


def _invention_from_run(task, u, v, model):
    """A model's invention for (task, u, v) from its run files: name and 'relation object' properties."""
    scores = json.loads((RUN / "scores" / model / "path_scores.json").read_text())
    resp = {(r["prompt_id"], r["sample_idx"]): r for r in json.loads((RUN / "responses" / model / "responses.json").read_text())}
    for r in scores:
        if r["mode"] != task or (r["u_label"], r["v_label"]) != (u, v):
            continue
        if task == "blending":
            it = (resp[(r["prompt_id"], r["sample_idx"])].get("items") or [{}])[0]
            return dict(model=model, name=it.get("concept") or r["triples"][0][0], properties=[f"{t[1]} {t[2]}" for t in r["triples"]])
        if r.get("invention"):
            it = next((i for i in resp[(r["prompt_id"], r["sample_idx"])]["items"] if i.get("invention") == r["invention"]), {})
            return dict(model=model, name=r["invention"], properties=[" ".join(pp["image"][1:]) for pp in it.get("projection", []) if len(pp.get("image", [])) >= 3])
    raise SystemExit(f"FATAL: no {task} invention for ({u}, {v}) in {model}")


def find_same_name(d, task, u, v, ma, mb):
    """The pair from the JSON's same-name examples if present, else built from the two models' run files
    (the pair must share a coined name, case-insensitively)."""
    for e in d["name_property_dissociation"]["examples_same_name_different_properties"]:
        if (e["task"], e["u"], e["v"]) != (task, u, v):
            continue
        if {e["a"]["model"], e["b"]["model"]} == {ma, mb}:
            a, b = (e["a"], e["b"]) if e["a"]["model"] == ma else (e["b"], e["a"])
            return dict(task=task, u=u, v=v, a=a, b=b)
    a, b = _invention_from_run(task, u, v, ma), _invention_from_run(task, u, v, mb)
    if " ".join(a["name"].lower().split()) != " ".join(b["name"].lower().split()):
        raise SystemExit(f"FATAL: ({task}, {u}, {v}) {ma} x {mb} do not share a name: {a['name']!r} vs {b['name']!r}")
    return dict(task=task, u=u, v=v, a=a, b=b)


def best_pairing(m, embed):
    """Best one-to-one pairing of the two property lists by cosine (Hungarian), as `matches` entries."""
    def vecs(props):
        M = np.asarray([embed(p) for p in props], float)
        return M / np.linalg.norm(M, axis=1, keepdims=True)
    S = vecs(m["a"]["properties"]) @ vecs(m["b"]["properties"]).T
    ri, ci = linear_sum_assignment(-S)
    return [{"a": int(i), "b": int(j), "cos": float(S[i, j])} for i, j in zip(ri, ci)]


def preamble():
    return [
        HEADER,
        "% Fragment (no float wrapper, no caption): \\input inside a table float; the caption and label",
        "% live in the section file next to the \\input.",
        r"\providecommand{\provlogo}[1]{\raisebox{-0.15ex}{\includegraphics[height=0.85em]{media/logos/#1}}\,}",
        # matched rows use one colour, the same-family slate of the tau-multiples figure (plot_tau_multiples.py SAME),
        # tinted multRow!<pct> (xcolor + colortbl); the figure keeps its salmon/peach task bars
        r"\definecolor{multRow}{HTML}{486878}",
        r"\definecolor{rowgrey}{HTML}{F2F2F2}",
        r"\scriptsize",
        r"\setlength{\tabcolsep}{2pt}",
        r"\renewcommand{\arraystretch}{1.05}",
    ]


def render(d, embed=None) -> str:
    """The multiples row; with an embedder, a second row of same-name pairs (best pairing, unshaded)."""
    picks = [find(d["multiples"], *spec) for spec in PAPER_PANELS]
    out = preamble() + ["\\hfill\n".join(one_table(m, letter, number=i + 1) for i, (m, letter) in enumerate(zip(picks, "abcdefgh")))]
    if embed is not None and SAME_NAME_PANELS:
        same = []
        for i, (spec, letter) in enumerate(zip(SAME_NAME_PANELS, "abcdefgh"[len(picks):])):
            m = find_same_name(d, *spec)
            m["matches"] = best_pairing(m, embed)
            same.append(one_table(m, letter, shade=False, kind="False Multiple", number=i + 1))
        out += ["", "\\vspace{6pt}", "", "\\hfill\n".join(same)]
    out.append("")
    return "\n".join(out)


def render_same_name(d, embed) -> str:
    same = []
    for i, (spec, letter) in enumerate(zip(SAME_NAME_PANELS, "abcdefgh")):
        m = find_same_name(d, *spec)
        m["matches"] = best_pairing(m, embed)
        same.append(one_table(m, letter, shade=False, kind="False Multiple", number=i + 1))
    return "\n".join(preamble() + ["\\hfill\n".join(same), ""])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("src", type=Path, help="inventive_multiples.json")
    ap.add_argument("dst", type=Path, help="output .tex fragment")
    ap.add_argument("--same-name-row", action="store_true",
                    help="also append the false-multiples row to the main fragment (default: they go only to tab_same_name_examples.tex, for the appendix)")
    a = ap.parse_args()
    d = json.loads(a.src.read_text())
    if "multiples" not in d:
        raise SystemExit(f"{a.src} has no `multiples` block -- re-run analyze_inventive_multiples.py")
    from src.kg_creat.embed import get_embedder
    embed = get_embedder("mlx-community/all-MiniLM-L6-v2-4bit")
    a.dst.write_text(render(d, embed if a.same_name_row else None))
    print(f"wrote {a.dst} ({len(PAPER_PANELS)} multiples tables" + (f" + {len(SAME_NAME_PANELS)} same-name tables below)" if a.same_name_row else ")"))
    dst2 = a.dst.with_name("tab_same_name_examples.tex")
    dst2.write_text(render_same_name(d, embed))
    print(f"wrote {dst2} ({len(SAME_NAME_PANELS)} same-name tables)")


if __name__ == "__main__":
    main()
