"""Emit the paper's showcase of judge-unanimous inventions as one LaTeX table.

Rows come from analysis/showcase_inventions.json (compile_showcase_inventions.py: every invention
all three panel judges passed). Which rows is an explicit choice (SHOWCASE below), not a ranking,
so the caption should say so. Columns: anchors (blend anchors coloured to match their property
chips), the coined name with the model, the generic space (blend) or projected source with its
source triples (analogy), and the properties -- blend properties carry a colour chip for their
provenance (input 1 / input 2 / fused / emergent), analogy properties are the image triples.

Float-less fragment, NO caption and NO label (captions are the author's, in the section file).

    .venv/bin/python -m src.kg_creat.scripts.make_showcase_table \\
        data/kg_creat/kombine_test30/analysis/showcase_inventions.json \\
        papers/kg_creat-iclr/media/tab_showcase_inventions.tex
"""
import argparse
import json
from pathlib import Path

from src.kg_creat.model_names import LOGO_SLUG, _provider

# (task, coined name): rows in table order. Four providers, no model repeated from the multiples tables.
SHOWCASE = [
    ("blending", "dharmic turbine"),
    ("blending", "Republic of Lucidity"),
    ("analogy", "judgment effect"),
    ("analogy", "testimonial soliloquy"),
]
HEADER = "% Auto-generated by make_showcase_table.py -- do not edit by hand."
TAG = {"u": "tu", "v": "tv", "uv": "tuv", "emergent": "tem"}


def tex(s: str) -> str:
    return (s.replace("\\", r"\textbackslash{}").replace("&", r"\&").replace("%", r"\%")
             .replace("_", r"\_").replace("#", r"\#").replace("$", r"\$"))


def model_cell(x) -> str:
    slug = LOGO_SLUG.get(_provider(x["model"]))
    return (f"\\provlogo{{{slug}}}" if slug else "") + tex(x["display"])


def row(x) -> str:
    if x["task"] == "blending":
        anchors = f"\\textcolor{{tu}}{{{tex(x['u'])}}} $+$ \\textcolor{{tv}}{{{tex(x['v'])}}}"
        mid = r"\emph{" + tex(x["generic_space"]) + "}"
        props = " \\newline ".join(f"\\tg{{{TAG[p['tag']]}}}{tex(p['relation'])} {tex(p['object'])}" for p in x["properties"])
    else:
        anchors = f"{tex(x['u'])} $::$ {tex(x['v'])}"
        mid = r"from \emph{" + tex(x["projected"]) + "}: \\newline " + " \\newline ".join(
            r"\textcolor{gray}{" + tex(" ".join(p["source"])) + "}" for p in x["projection"])
        props = " \\newline ".join(tex(" ".join(p["image"])) for p in x["projection"])
    return f"{anchors} & \\textbf{{``{tex(x['name'])}''}} \\newline {model_cell(x)} & {mid} & {props} \\\\ \\addlinespace"


def render(rows) -> str:
    L = [HEADER,
         "% Fragment (no float wrapper, no caption): \\input inside a table float; the caption and label",
         "% live in the section file next to the \\input.",
         r"\providecommand{\provlogo}[1]{\raisebox{-0.15ex}{\includegraphics[height=0.85em]{media/logos/#1}}\,}",
         r"\definecolor{tu}{HTML}{2F6B9A}\definecolor{tv}{HTML}{C46A2A}\definecolor{tuv}{HTML}{4E8A3E}\definecolor{tem}{HTML}{7B4FA3}",
         r"\providecommand{\tg}[1]{\textcolor{#1}{\rule{0.9ex}{0.9ex}}\,}",
         r"\scriptsize",
         r"\setlength{\tabcolsep}{4pt}",
         r"\renewcommand{\arraystretch}{1.12}",
         r"\begin{tabular}{@{}>{\raggedright\arraybackslash}p{0.13\linewidth}>{\raggedright\arraybackslash}p{0.17\linewidth}"
         r">{\raggedright\arraybackslash}p{0.29\linewidth}>{\raggedright\arraybackslash}p{0.35\linewidth}@{}}",
         r"\toprule",
         r"Anchors & Invention & Generic space / projected source & Properties \\",
         r"\midrule"]
    L += [row(x) for x in rows]
    L += [r"\bottomrule", r"\end{tabular}", "",
          r"\vspace{3pt}{\scriptsize \tg{tu}\,/\,\tg{tv} from the input of that colour \quad \tg{tuv} fused \quad \tg{tem} emergent}", ""]
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("src", type=Path)
    ap.add_argument("dst", type=Path)
    a = ap.parse_args()
    data = json.loads(a.src.read_text())
    rows = []
    for task, name in SHOWCASE:
        m = [x for x in data if x["task"] == task and x["name"] == name]
        if len(m) != 1:
            raise SystemExit(f"FATAL: ({task}, {name!r}) matches {len(m)} showcase inventions")
        rows.append(m[0])
    a.dst.write_text(render(rows))
    print(f"wrote {a.dst} ({len(rows)} rows: " + "; ".join(f"{x['name']} [{x['display']}]" for x in rows) + ")")


if __name__ == "__main__":
    main()
