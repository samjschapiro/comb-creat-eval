"""Emit the paper's showcase of judge-unanimous inventions as one LaTeX table.

Rows come from analysis/showcase_inventions.json (compile_showcase_inventions.py: every invention
all three panel judges passed). Which rows is an explicit choice (SHOWCASE below), not a ranking,
so the caption should say so. Columns: anchors (blend anchors coloured to match their property
chips), the coined name with the model, the generic space (blend) or projected source with its
source triples (analogy), and the properties -- blend properties carry a colour chip for their
provenance (input 1 / input 2 / fused / emergent), analogy properties are the image triples.

Float-less fragment, NO caption and NO label (captions are the author's, in the section file).

    .venv/bin/python -m src.kg_creat.scripts.make_showcase_table \\
        data/kg_creat/kombine_test30/analysis/showcase_inventions.json \\
        papers/kg_creat-iclr/media/tab_showcase_inventions.tex
"""
import argparse
import json
from pathlib import Path

from src.kg_creat.model_names import DISPLAY, LOGO_SLUG, _provider

# (task, coined name[, model]): rows in table order, chosen by hand (the user's picks, 2026-09-13). A
# third element names the model when the invention is NOT in the judge-unanimous JSON and must be read
# from that model's response/score files instead (whale groomer drone: the human study's worked
# example; GPT-5.4 judged it valid but not coherent, the other two judges passed it).
SHOWCASE = [
    ("analogy", "Accountability bond"),                           # officials post a bond forfeited on abuse of power
    ("analogy", "whale groomer drone", "anthropic_claude-fable-5"),  # a vacuum cleaner for the blue whale
]
# --images: an illustration per row (generated with gpt-5-image; prompts in scratch/showcase_inventions/
# gen_images.py) in a fifth column, vertically centred against its row, so the table is the centrepiece
# and the pictures sit beside their inventions.
IMAGES = {
    "Accountability bond": "media/figures/04a_accountability_bond.png",
    "whale groomer drone": "media/figures/04b_whale_groomer_drone.png",
}
RUN = Path("data/kg_creat/kombine_test30")
HEADER = "% Auto-generated by make_showcase_table.py -- do not edit by hand."
TAG = {"u": "tu", "v": "tv", "uv": "tuv", "emergent": "tem"}


def tex(s: str) -> str:
    s = s.replace("_", " ")          # kimi-k2 writes snake_case ("Moral_refresher", "administered_after"): show as words
    return (s.replace("\\", r"\textbackslash{}").replace("&", r"\&").replace("%", r"\%")
             .replace("_", r"\_").replace("#", r"\#").replace("$", r"\$"))


def model_cell(x) -> str:
    slug = LOGO_SLUG.get(_provider(x["model"]))
    return (f"\\provlogo{{{slug}}}" if slug else "") + tex(x["display"])


def row(x, letter=None, image=None) -> str:
    if x["task"] == "blending":
        anchors = f"\\textcolor{{tu}}{{{tex(x['u'])}}} $+$ \\textcolor{{tv}}{{{tex(x['v'])}}}"
        mid = r"\emph{" + tex(x["generic_space"]) + "}"
        props = " \\newline ".join(f"\\tg{{{TAG[p['tag']]}}}{tex(p['relation'])} {tex(p['object'])}" for p in x["properties"])
    else:
        anchors = f"{tex(x['u'])} $::$ {tex(x['v'])}"
        mid = r"from \emph{" + tex(x["projected"]) + "}: \\newline " + " \\newline ".join(
            r"\textcolor{gray}{" + tex(" ".join(p["source"])) + "}" for p in x["projection"])
        props = " \\newline ".join(tex(" ".join(p["image"])) for p in x["projection"])
    if letter:
        anchors = f"\\textbf{{({letter})}} {anchors}"
    cells = f"{anchors} & \\textbf{{``{tex(x['name'])}''}} \\newline {model_cell(x)} & {mid} & {props}"
    if image:
        cells += f" & \\includegraphics[width=\\linewidth]{{{image}}}"
    return cells + " \\\\ \\addlinespace"


def render(rows, images=False) -> str:
    L = [HEADER,
         "% Fragment (no float wrapper, no caption): \\input inside a table float; the caption and label",
         "% live in the section file next to the \\input.",
         r"\providecommand{\provlogo}[1]{\raisebox{-0.15ex}{\includegraphics[height=0.85em]{media/logos/#1}}\,}",
         r"\definecolor{tu}{HTML}{2F6B9A}\definecolor{tv}{HTML}{C46A2A}\definecolor{tuv}{HTML}{4E8A3E}\definecolor{tem}{HTML}{7B4FA3}",
         r"\providecommand{\tg}[1]{\textcolor{#1}{\rule{0.9ex}{0.9ex}}\,}",
         r"\scriptsize",
         r"\setlength{\tabcolsep}{4pt}",
         r"\renewcommand{\arraystretch}{1.12}",
         ]
    if images:      # four text columns at ~0.65 of the line, the picture column at 0.26, all vertically centred
        L += [r"\begin{tabular}{@{}>{\raggedright\arraybackslash}m{0.09\linewidth}>{\raggedright\arraybackslash}m{0.12\linewidth}"
              r">{\raggedright\arraybackslash}m{0.20\linewidth}>{\raggedright\arraybackslash}m{0.24\linewidth}@{\hspace{6pt}}m{0.26\linewidth}@{}}",
              r"\toprule",
              r"Anchors & Invention & Projected source & Properties & \\",
              r"\midrule"]
        L += [row(x, letter, IMAGES.get(x["name"])) for x, letter in zip(rows, "abcdefgh")]
    else:
        L += [r"\begin{tabular}{@{}>{\raggedright\arraybackslash}p{0.13\linewidth}>{\raggedright\arraybackslash}p{0.17\linewidth}"
              r">{\raggedright\arraybackslash}p{0.29\linewidth}>{\raggedright\arraybackslash}p{0.35\linewidth}@{}}",
              r"\toprule",
              r"Anchors & Invention & Generic space / projected source & Properties \\",
              r"\midrule"]
        L += [row(x) for x in rows]
    L += [r"\bottomrule", r"\end{tabular}", ""]
    if any(x["task"] == "blending" for x in rows):        # the chip legend only matters when a blend row is present
        L += [r"\vspace{3pt}{\scriptsize \tg{tu}\,/\,\tg{tv} from the input of that colour \quad \tg{tuv} fused \quad \tg{tem} emergent}", ""]
    return "\n".join(L)


def from_run(task, name, model):
    """Build a showcase row for an invention that is not in the unanimous JSON, from the run files."""
    scores = json.loads((RUN / "scores" / model / "path_scores.json").read_text())
    resp = {(r["prompt_id"], r["sample_idx"]): r for r in json.loads((RUN / "responses" / model / "responses.json").read_text())}
    for r in scores:
        if r["mode"] == task and (r.get("invention") if task == "analogy" else None) == name:
            it = next(i for i in resp[(r["prompt_id"], r["sample_idx"])]["items"] if i.get("invention") == name)
            return dict(task=task, model=model, display=DISPLAY.get(model, model), u=r["u_label"], v=r["v_label"], name=name,
                        originality=r.get("originality"), projected=it.get("projected"),
                        projection=[dict(source=p["source"], image=p["image"]) for p in it["projection"]])
    raise SystemExit(f"FATAL: ({task}, {name!r}) not found in {model}'s run files")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("src", type=Path)
    ap.add_argument("dst", type=Path)
    ap.add_argument("--images", action="store_true", help="add the illustration column (paper figure layout)")
    a = ap.parse_args()
    data = json.loads(a.src.read_text())
    rows = []
    for spec in SHOWCASE:
        task, name = spec[0], spec[1]
        m = [x for x in data if x["task"] == task and x["name"] == name]
        if len(spec) == 3 and not m:
            m = [from_run(task, name, spec[2])]
        if len(m) != 1:
            raise SystemExit(f"FATAL: ({task}, {name!r}) matches {len(m)} showcase inventions")
        rows.append(m[0])
    a.dst.write_text(render(rows, images=a.images))
    print(f"wrote {a.dst} ({len(rows)} rows: " + "; ".join(f"{x['name']} [{x['display']}]" for x in rows) + ")")


if __name__ == "__main__":
    main()
