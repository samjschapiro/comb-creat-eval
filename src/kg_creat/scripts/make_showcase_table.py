"""Emit the paper's showcase of judge-unanimous inventions as one LaTeX table.

Rows come from analysis/showcase_inventions.json (compile_showcase_inventions.py: every invention
all three panel judges passed). Which rows is an explicit choice (SHOWCASE below), not a ranking,
so the caption should say so. Columns: anchors (blend anchors coloured to match their property
chips), the coined name with the model, the generic space (blend) or projected source with its
source triples (analogy), and the properties -- blend properties carry a colour chip for their
provenance (input 1 / input 2 / fused / emergent), analogy properties are the image triples.

Float-less fragment, NO caption and NO label (captions are the author's, in the section file).

    .venv/bin/python -m src.kg_creat.scripts.make_showcase_table \\
        data/kg_creat/kombine_test30/analysis/showcase_inventions.json \\
        papers/kg_creat-iclr/media/tab_showcase_inventions.tex
"""
import argparse
import json
from pathlib import Path

from src.kg_creat.model_names import DISPLAY, LOGO_SLUG, _provider

# (task, coined name[, model]): rows in table order, chosen by hand (the user's picks, 2026-09-13). A
# third element names the model when the invention is NOT in the judge-unanimous JSON and must be read
# from that model's response/score files instead (whale groomer drone: the human study's worked
# example; GPT-5.4 judged it valid but not coherent, the other two judges passed it).
# The association row is carried over verbatim from the paper's original Table 3 (that path is not in
# the kombine_test30 run files), so it is a literal LaTeX row rather than a lookup.
SHOWCASE = [
    ("association", "Radio -> The Milky Way", "anthropic_claude-opus-5", "Starry Night"),   # a fully factual 4-hop path, matched by a substring
    ("analogy", "whale groomer drone", "anthropic_claude-fable-5"),                          # a vacuum cleaner for the blue whale
    ("blending", "market colony", "anthropic_claude-opus-4-5"),                              # judge-unanimous; bacteria as a market without a planner
]
ASSOCIATION_ROW_LEGACY = (r"Association \newline (gpt-5)", r"\textbf{Anchors} $(u,v)$: \textcolor{domA}{\emph{Democracy}} $\to$ \textcolor{domB}{\emph{Banking}}. \newline "
                   r"\textbf{Path} $(p)$: (\textcolor{domA}{Democracy}, upholds, the rule of law) $\to$ (the rule of law, enforces, property rights) $\to$ (property rights, enable, \textcolor{domB}{Banking}).")
# --images: an illustration per row (generated with gpt-5-image; prompts in scratch/showcase_inventions/
# gen_images.py) in a further column, vertically centred against its row, so the table is the centrepiece
# and the pictures sit beside their inventions.
IMAGES = {
    "whale groomer drone": "media/figures/tab_examples_b_whale_groomer_drone.png",
    "market colony": "media/figures/tab_examples_c_market_colony.png",
}
RUN = Path("data/kg_creat/kombine_test30")
HEADER = "% Auto-generated by make_showcase_table.py -- do not edit by hand."
TAG = {"u": "tu", "v": "tv", "uv": "tuv", "emergent": "tem"}


def tex(s: str) -> str:
    s = s.replace("_", " ")          # kimi-k2 writes snake_case ("Moral_refresher", "administered_after"): show as words
    return (s.replace("\\", r"\textbackslash{}").replace("&", r"\&").replace("%", r"\%")
             .replace("_", r"\_").replace("#", r"\#").replace("$", r"\$"))


def model_cell(x) -> str:
    slug = LOGO_SLUG.get(_provider(x["model"]))
    return (f"\\provlogo{{{slug}}}" if slug else "") + tex(x["display"])


def row(x, letter=None, image=None) -> str:
    if x["task"] == "blending":
        anchors = f"\\textcolor{{tu}}{{{tex(x['u'])}}} $+$ \\textcolor{{tv}}{{{tex(x['v'])}}}"
        mid = r"\emph{" + tex(x["generic_space"]) + "}"
        props = " \\newline ".join(f"\\tg{{{TAG[p['tag']]}}}{tex(p['relation'])} {tex(p['object'])}" for p in x["properties"])
    else:
        anchors = f"{tex(x['u'])} $::$ {tex(x['v'])}"
        mid = r"from \emph{" + tex(x["projected"]) + "}: \\newline " + " \\newline ".join(
            r"\textcolor{gray}{" + tex(" ".join(p["source"])) + "}" for p in x["projection"])
        props = " \\newline ".join(tex(" ".join(p["image"])) for p in x["projection"])
    if letter:
        anchors = f"\\textbf{{({letter})}} {anchors}"
    cells = f"{anchors} & \\textbf{{``{tex(x['name'])}''}} \\newline {model_cell(x)} & {mid} & {props}"
    if image:
        cells += f" & \\includegraphics[width=\\linewidth]{{{image}}}"
    return cells + " \\\\ \\addlinespace"


def render(rows, images=False) -> str:
    L = [HEADER,
         "% Fragment (no float wrapper, no caption): \\input inside a table float; the caption and label",
         "% live in the section file next to the \\input.",
         r"\providecommand{\provlogo}[1]{\raisebox{-0.15ex}{\includegraphics[height=0.85em]{media/logos/#1}}\,}",
         r"\definecolor{tu}{HTML}{2F6B9A}\definecolor{tv}{HTML}{C46A2A}\definecolor{tuv}{HTML}{4E8A3E}\definecolor{tem}{HTML}{7B4FA3}",
         r"\providecommand{\tg}[1]{\textcolor{#1}{\rule{0.9ex}{0.9ex}}\,}",
         r"\scriptsize",
         r"\setlength{\tabcolsep}{4pt}",
         r"\renewcommand{\arraystretch}{1.12}",
         ]
    if images:      # four text columns at ~0.65 of the line, the picture column at 0.26, all vertically centred
        L += [r"\begin{tabular}{@{}>{\raggedright\arraybackslash}m{0.09\linewidth}>{\raggedright\arraybackslash}m{0.12\linewidth}"
              r">{\raggedright\arraybackslash}m{0.20\linewidth}>{\raggedright\arraybackslash}m{0.24\linewidth}@{\hspace{6pt}}m{0.26\linewidth}@{}}",
              r"\toprule",
              r"Anchors & Invention & Projected source & Properties & \\",
              r"\midrule"]
        L += [row(x, letter, IMAGES.get(x["name"])) for x, letter in zip(rows, "abcdefgh")]
    else:
        L += [r"\begin{tabular}{@{}>{\raggedright\arraybackslash}p{0.13\linewidth}>{\raggedright\arraybackslash}p{0.17\linewidth}"
              r">{\raggedright\arraybackslash}p{0.29\linewidth}>{\raggedright\arraybackslash}p{0.35\linewidth}@{}}",
              r"\toprule",
              r"Anchors & Invention & Generic space / projected source & Properties \\",
              r"\midrule"]
        L += [row(x) for x in rows]
    L += [r"\bottomrule", r"\end{tabular}", ""]
    if any(x["task"] == "blending" for x in rows):        # the chip legend only matters when a blend row is present
        L += [r"\vspace{3pt}{\scriptsize \tg{tu}\,/\,\tg{tv} from the input of that colour \quad \tg{tuv} fused \quad \tg{tem} emergent}", ""]
    return "\n".join(L)


def aligned_paths(x):
    """The two aligned paths (p_u, p_v) the model built before projecting, from its response file."""
    resp = json.loads((RUN / "responses" / x["model"] / "responses.json").read_text())
    for r in resp:
        if r["mode"] != "analogy":
            continue
        for it in r.get("items", []):
            if it.get("invention") == x["name"] and r["u_label"] == x["u"] and r["v_label"] == x["v"]:
                return it["paths"][0], it["paths"][1]
    raise SystemExit(f"FATAL: no aligned paths for {x['name']!r} in {x['model']}")


def from_run(task, name, model, match=None):
    """Build a showcase row from the run files: an analogy invention or blend concept by name, or an
    association path by anchors ("u -> v") plus a substring that must occur in its triples."""
    scores = json.loads((RUN / "scores" / model / "path_scores.json").read_text())
    resp = {(r["prompt_id"], r["sample_idx"]): r for r in json.loads((RUN / "responses" / model / "responses.json").read_text())}
    base = dict(model=model, display=DISPLAY.get(model, model))
    if task == "association":
        u, v = [t.strip() for t in name.split("->")]
        for r in scores:
            if r["mode"] == "baseline" and r["u_label"] == u and r["v_label"] == v and match in json.dumps(r["triples"]):
                return dict(base, task="association", u=u, v=v, name=name, originality=r.get("originality"), triples=r["triples"], factual=r.get("factual"))
        raise SystemExit(f"FATAL: no association path {name!r} containing {match!r} in {model}")
    if task == "blending":
        for r in scores:
            if r["mode"] != "blending":
                continue
            it = (resp[(r["prompt_id"], r["sample_idx"])].get("items") or [{}])[0]
            if (it.get("concept") or r["triples"][0][0]) == name:
                return dict(base, task="blending", u=r["u_label"], v=r["v_label"], name=name, originality=r.get("originality"),
                            generic_space=it.get("generic_space"),
                            properties=[dict(relation=t[1], object=t[2], tag=g) for t, g in zip(r["triples"], it.get("tags") or [])])
        raise SystemExit(f"FATAL: blend {name!r} not found in {model}")
    for r in scores:
        if r["mode"] == task and (r.get("invention") if task == "analogy" else None) == name:
            it = next(i for i in resp[(r["prompt_id"], r["sample_idx"])]["items"] if i.get("invention") == name)
            return dict(task=task, model=model, display=DISPLAY.get(model, model), u=r["u_label"], v=r["v_label"], name=name,
                        originality=r.get("originality"), projected=it.get("projected"),
                        projection=[dict(source=p["source"], image=p["image"]) for p in it["projection"]])
    raise SystemExit(f"FATAL: ({task}, {name!r}) not found in {model}'s run files")


def _c(col, txt): return f"\\textcolor{{{col}}}{{{txt}}}"


def triple(t, col_map):
    """(s, r, o) with each entity coloured by the domain it belongs to (col_map: entity -> colour)."""
    def ent(e): return _c(col_map[e], tex(e)) if e in col_map else tex(e)
    return f"({ent(t[0])}, {tex(t[1])}, {ent(t[2])})"


def examples_row(x, letter, image=None) -> str:
    """One analogy in the format of the paper's Table 3 (example outputs on each task)."""
    pu, pv = aligned_paths(x)
    nodes_u = {e for t in pu for e in (t[0], t[2])} | {x["u"]}
    nodes_v = {e for t in pv for e in (t[0], t[2])} | {x["v"]}
    src = x["projected"]
    # the source domain is whichever path the source triples' objects come from
    objs = [p["source"][2] for p in x["projection"]]
    src_is_v = sum(o in nodes_v for o in objs) >= sum(o in nodes_u for o in objs)
    src_col, tgt_col = ("domB", "domA") if src_is_v else ("domA", "domB")
    col = {e: "domA" for e in nodes_u}; col.update({e: "domB" for e in nodes_v})
    col[src] = src_col; col[x["name"]] = "invCol"
    bs = chr(92)
    L = [f"{bs}textbf{{Anchors}} $(u,v)$: {_c('domA', bs + 'emph{' + tex(x['u']) + '}')} $::$ {_c('domB', bs + 'emph{' + tex(x['v']) + '}')}.",
         _c("domA", f"{bs}textbf{{Path a}} $(p_u)$: " + ", ".join(f"({tex(t[0])}, {tex(t[1])}, {tex(t[2])})" for t in pu)) + ".",
         _c("domB", f"{bs}textbf{{Path b}} $(p_v)$: " + ", ".join(f"({tex(t[0])}, {tex(t[1])}, {tex(t[2])})" for t in pv)) + ".",
         f"{bs}textbf{{Source}} $({bs}varphi)$: {_c(src_col, tex(src))} (from {tex(x['v'] if src_is_v else x['u'])}, no counterpart in {tex(x['u'] if src_is_v else x['v'])}).",
         f"{bs}textbf{{Invention}} $(h {bs}gets M[{bs}varphi])$: {_c('invCol', bs + 'textbf{' + tex(x['name']) + '}')}.",
         f"{bs}textbf{{Source to Target Mapping}} $(M^{{u, v}})$:"]
    L += [f"{triple(p['source'], col)} ${bs}mapsto$ {triple(p['image'], col)}" for p in x["projection"]]
    body = f" {bs}newline\n".join(L)
    label = f"{bs}textbf{{({letter})}} Analogy {bs}newline ({tex(x['display'])})"
    cells = f"{label} & {body}"
    if image:
        cells += f" & {bs}includegraphics[width={bs}linewidth]{{{image}}}"
    return cells + f" {bs}{bs}"


def association_row(x, letter, image=None) -> str:
    """One association path in the format of the paper's Table 3."""
    bs = chr(92)
    col = {x["u"]: "domA", x["v"]: "domB"}
    path = f" ${bs}to$ ".join(triple(t, col) for t in x["triples"])
    body = (f"{bs}textbf{{Anchors}} $(u,v)$: {_c('domA', bs + 'emph{' + tex(x['u']) + '}')} ${bs}to$ {_c('domB', bs + 'emph{' + tex(x['v']) + '}')}. {bs}newline\n"
            f"{bs}textbf{{Path}} $(p)$: {path}.")
    label = f"{bs}textbf{{({letter})}} Association {bs}newline ({tex(x['display'])})"
    cells = f"{label} & {body}"
    if image:
        cells += f" & {bs}includegraphics[width={bs}linewidth]{{{image}}}"
    elif IMAGES:
        cells += " &"
    return cells + f" {bs}{bs}"


def blend_row(x, letter, image=None) -> str:
    """One blend in the format of the paper's Table 3: generic space, invention, blended space with tags."""
    bs = chr(92)
    tagc = {"u": ("domA", "[u]"), "v": ("domB", "[v]"), "uv": ("invCol", "[uv]"), "emergent": ("emCol", "[\\emph{emergent}]")}
    L = [f"{bs}textbf{{Anchors}} $(u,v)$: {_c('domA', bs + 'emph{' + tex(x['u']) + '}')} $+$ {_c('domB', bs + 'emph{' + tex(x['v']) + '}')}.",
         f"{bs}textbf{{Generic Space}} $(g)$: {tex(x['generic_space'])}.",
         f"{bs}textbf{{Invention}} $(b)$: {_c('invCol', bs + 'textbf{' + tex(x['name']) + '}')}.",
         f"{bs}textbf{{Blended Space}} $(c')$, each row tagged by its projection:"]
    for pr in x["properties"]:
        col, tag = tagc[pr["tag"]]
        trip = f"({_c('invCol', tex(x['name']))}, {tex(pr['relation'])}, {tex(pr['object'])})"
        L.append((_c("emCol", trip) if pr["tag"] == "emergent" else trip) + f"~{_c(col, tag)}")
    body = f" {bs}newline\n".join(L)
    label = f"{bs}textbf{{({letter})}} Blending {bs}newline ({tex(x['display'])})"
    cells = f"{label} & {body}"
    if image:
        cells += f" & {bs}includegraphics[width={bs}linewidth]{{{image}}}"
    return cells + f" {bs}{bs}"


def render_examples(rows, images=False) -> str:
    L = [HEADER,
         "% Fragment (no float wrapper, no caption), in the format of tab_examples.tex: \\input inside a figure/table float.",
         r"\providecommand{\provlogo}[1]{\raisebox{-0.15ex}{\includegraphics[height=0.85em]{media/logos/#1}}\,}",
         r"\definecolor{domA}{HTML}{3F6F8E}\definecolor{domB}{HTML}{765030}\definecolor{invCol}{HTML}{22394F}\definecolor{emCol}{HTML}{B74D34}",
         r"{\scriptsize", r"\renewcommand{\arraystretch}{1.3}",
         r"\renewcommand\tabularxcolumn[1]{m{#1}}"]
    if images:
        L += [r"\begin{tabularx}{\textwidth}{@{}m{2.1cm} X @{\hspace{6pt}}m{0.20\linewidth}@{}}", r"\toprule",
              r"\textbf{Task (model)} & \textbf{Example output} & \textbf{Illustration} \\", r"\midrule"]
    else:
        L += [r"\begin{tabularx}{\textwidth}{@{}m{2.1cm} X@{}}", r"\toprule",
              r"\textbf{Task (model)} & \textbf{Example output} \\", r"\midrule"]
    body = []
    for x, letter in zip(rows, "abcdefgh"):
        img = IMAGES.get(x["name"]) if images else None
        if x["task"] == "association":
            body.append(association_row(x, letter, img) if "triples" in x else
                        f"\\textbf{{({letter})}} {ASSOCIATION_ROW_LEGACY[0]} & {ASSOCIATION_ROW_LEGACY[1]}" + (" &" if images else "") + " \\\\")
        elif x["task"] == "blending":
            body.append(blend_row(x, letter, img))
        else:
            body.append(examples_row(x, letter, img))
    L.append("\n\\midrule\n".join(body))
    L += [r"\bottomrule", r"\end{tabularx}", "}", ""]
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("src", type=Path)
    ap.add_argument("dst", type=Path)
    ap.add_argument("--images", action="store_true", help="add the illustration column (paper figure layout)")
    ap.add_argument("--style", choices=["columns", "examples"], default="columns",
                    help="columns: one column per field; examples: the paper's Table 3 format (paths, source, invention, mapping)")
    a = ap.parse_args()
    data = json.loads(a.src.read_text())
    rows = []
    for spec in SHOWCASE:
        task, name = spec[0], spec[1]
        if task == "association" and len(spec) == 2:
            rows.append(dict(task="association", name=name, display="gpt-5")); continue
        m = [x for x in data if x["task"] == task and x["name"] == name and (len(spec) < 3 or x["model"] == spec[2])]
        if len(spec) >= 3 and not m:
            m = [from_run(task, name, spec[2], spec[3] if len(spec) > 3 else None)]
        if len(m) != 1:
            raise SystemExit(f"FATAL: ({task}, {name!r}) matches {len(m)} showcase inventions")
        rows.append(m[0])
    a.dst.write_text(render_examples(rows, images=a.images) if a.style == "examples" else render(rows, images=a.images))
    print(f"wrote {a.dst} ({len(rows)} rows: " + "; ".join(f"{x['name']} [{x['display']}]" for x in rows) + ")")


if __name__ == "__main__":
    main()
