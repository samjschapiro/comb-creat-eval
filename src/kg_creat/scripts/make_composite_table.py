"""Render the Kombine leaderboard table (top systems per task) from ``composite.json``.

Mirrors the TwistBench ``tab_pctl_top`` format: a Rank column plus one column per view
(Overall / Association / Analogy / Blending); each cell is ``model~(+z)``, with each column
independently ranked by that view's z-composite. Writes a self-contained,
top-aligned ``table[t]`` LaTeX fragment.

    python src/kg_creat/scripts/make_composite_table.py \\
        data/kg_creat/kombine_v1/scores/composite.json \\
        papers/kg_creat-iclr/media/tab_leaderboard.tex
"""

import argparse
import json
from pathlib import Path

# Display names come from the shared map, not a local copy: this file's copy had drifted 9 models
# behind the pool and printed raw keys for every model added since.
from src.kg_creat.model_names import DISPLAY  # noqa: E402
VIEWS = [("Overall", "overall"), ("Association", "association"),
         ("Analogy", "analogy"), ("Blending", "blending")]


def _name(key):
    return DISPLAY.get(key, key.replace("_", "/"))


# provider -> logo file stem in media/logos/ (rendered from assets/logos by render_logos.py)
PROV_SLUG = {"openai": "openai", "anthropic": "claude", "google": "googlegemini", "x-ai": "xai",
             "deepseek": "deepseek", "qwen": "qwen", "z-ai": "zai", "meta-llama": "meta",
             "moonshotai": "kimi", "microsoft": "microsoft"}


def _logo(key):
    return next((s for p, s in PROV_SLUG.items() if key.startswith(p)), None)


def _ordinal(n):
    return f"{n}{'th' if 11 <= n % 100 <= 13 else {1: 'st', 2: 'nd', 3: 'rd'}.get(n % 10, 'th')}"


def human_rows(human: dict, rows: dict) -> list:
    """A second block below the top-N, in the same "rank & name~(score)" format: every column ranks the models
    together with the kept human participants,
    and the block shows only the ranks at which a human group appears in some column (vdots mark skipped ranks).

    ``human`` is the human-study composite on the shared human + model originality pool with skipped items
    counted as failed (data/kg_creat/human_study/combined_scores_skip0/composite.json); ``rows`` is
    analysis/human_vs_models.json["human_rows"] (the two groups' scores)."""
    pm = human["per_model"]
    score = {m: {"overall": pm[m]["overall"], **pm[m]["per_task"]} for m in pm if not m.startswith("human")}
    labels = {"all": "Humans"}   # all kept participants (the comprehension-screened subset is reported in the text only)
    for k, lab in labels.items():
        score[lab] = {v: rows[k][v]["score"] for _, v in VIEWS}
    ranked = {v: sorted(score, key=lambda m: score[m][v], reverse=True) for _, v in VIEWS}
    first = min(ranked[v].index(lab) for _, v in VIEWS for lab in labels.values())

    def cell(m, v):
        if m in labels.values():
            return f"\\textit{{{m}}}~({score[m][v]:.1f})"
        logo = _logo(m)
        return (f"\\provlogo{{{logo}}}" if logo else "") + f"{_name(m)}~({score[m][v]:.1f})"
    # only the ranks at which a human group appears in some column; skipped ranks are marked with a vdots row
    show = sorted({ranked[v].index(lab) for _, v in VIEWS for lab in labels.values()})
    vdots = "\\multicolumn{5}{c}{$\\vdots$} \\\\"
    out, prev = ["\\midrule"], None
    for i in show:
        if prev is None or i != prev + 1:
            out.append(vdots)
        out.append(f"{i + 1} & " + " & ".join(cell(ranked[v][i], v) for _, v in VIEWS) + " \\\\")
        prev = i
    return out


def render(composite: dict, top_n: int = 10, human: dict | None = None) -> str:
    pm = composite["per_model"]
    models = composite["models"]

    def score(m, view):
        return pm[m]["overall"] if view == "overall" else pm[m]["per_task"].get(view)

    # each column: models ranked by that view's z (drop undefined), top_n
    cols = {}
    for _, view in VIEWS:
        ranked = sorted((m for m in models if score(m, view) is not None),
                        key=lambda m: score(m, view), reverse=True)
        cols[view] = ranked[:top_n]
    n_rows = max(len(c) for c in cols.values())

    lines = [
        "% Auto-generated by make_composite_table.py -- do not edit by hand.",
        "% Fragment (no float wrapper): \\input inside a table float so it stays directly above the",
        "% examples table (\\captionof needs the caption package).",
        "\\captionof{table}{\\textbf{Top systems by combinatorial creativity.} The highest-scoring models on "
        "\\textit{Overall} and on each task, by the equal-weight per-dimension composite "
        "(\\Cref{sec:benchmark}), reported as a \\% of the maximum score. Each column is ranked "
        "independently; parenthetical values are that column's score (\\%).}",
        "\\label{tab:leaderboard}",
        "\\providecommand{\\provlogo}[1]{\\raisebox{-0.15ex}{\\includegraphics[height=0.85em]{media/logos/#1}}\\,}",
        "{\\footnotesize",
        "\\setlength{\\tabcolsep}{5pt}",
        "\\resizebox{\\textwidth}{!}{%",
        "\\begin{tabular}{r" + "l" * len(VIEWS) + "}",
        "\\toprule",
        "Rank & " + " & ".join(f"\\textbf{{{h}}}" for h, _ in VIEWS) + " \\\\",
        "\\midrule",
    ]
    for i in range(n_rows):
        cells = []
        for _, view in VIEWS:
            ranked = cols[view]
            if i < len(ranked):
                m = ranked[i]
                lg = _logo(m)
                pre = f"\\provlogo{{{lg}}}" if lg else ""
                cells.append(f"{pre}{_name(m)}~({score(m, view):.1f})")
            else:
                cells.append("")
        lines.append(f"{i + 1} & " + " & ".join(cells) + " \\\\")
    lines += human_rows(*human) if human else []
    lines += ["\\bottomrule", "\\end{tabular}}", "}", ""]
    return "\n".join(lines)


def main(composite_path, out_path, top_n, human_path=None):
    composite = json.loads(Path(composite_path).read_text())
    human = ((json.loads(Path(human_path).read_text()),
              json.loads(Path("data/kg_creat/human_study/analysis/human_vs_models.json").read_text())["human_rows"])
             if human_path else None)
    tex = render(composite, top_n, human)
    Path(out_path).write_text(tex)
    print(f"Wrote {out_path} ({composite['per_model'].__len__()} models, top {top_n}/column)")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("composite_path")
    ap.add_argument("out_path")
    ap.add_argument("--top_n", type=int, default=10)
    ap.add_argument("--human", default=None,
                    help="human-study composite (data/kg_creat/human_study/combined_scores_skip0/composite.json): "
                         "adds a second block where both human groups are ranked among the models")
    args = ap.parse_args()
    main(args.composite_path, args.out_path, args.top_n, args.human)
