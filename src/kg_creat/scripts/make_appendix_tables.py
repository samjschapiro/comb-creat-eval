"""Render appendix tables from composite.json (the % of maximum / stationary scale, matching the main
leaderboard, \\Cref{tab:leaderboard}):
  (1) the FULL leaderboard -- every model, overall + per-task composite;
  (2) three per-task tables -- every model x that task's scoring dimensions.

    python src/kg_creat/scripts/make_appendix_tables.py \\
        data/kg_creat/kombine_test30/scores/composite.json papers/kg_creat-iclr/media/03_per_task_full.tex
"""
import argparse
import json
from pathlib import Path

from src.kg_creat.scripts.make_composite_table import DISPLAY
from src.kg_creat.scripts.plot_radar import LOGO_SLUG, _provider

# Provider logos shipped with the paper. microsoft and moonshotai have no asset, so their models
# render as the name alone rather than a broken \includegraphics.
LOGO_DIR = Path(__file__).resolve().parents[3] / "papers" / "kg_creat-iclr" / "media" / "logos"

# Shrink a table only if it would overrun the text block; \resizebox alone would also blow up a
# narrow table to full width. Needs only graphicx, which the paper already loads.
FIT_OPEN = r"\resizebox{\ifdim\width>\linewidth\linewidth\else\width\fi}{!}{%"
FIT_CLOSE = r"}"

# (task label, internal key, [(dim key, column header)]) -- emergent split into its two dimensions.
TASKS = [
    ("Association", "association", [("utility", "Utility"), ("surprise", "Surprise"),
                                    ("originality", "Originality")]),
    ("Analogy", "analogy", [("utility", "Utility"), ("surprise", "Surprise"),
                            ("originality", "Orig.\\ (base)"), ("em_originality", "Orig.\\ (emrg.)"),
                            ("em_integration", "Emerg.\\ integ."), ("em_utility", "Emerg.\\ util.")]),
    ("Blending", "blending", [("utility", "Utility"), ("surprise", "Surprise"),
                              ("originality", "Orig.\\ (base)"), ("em_originality", "Orig.\\ (emrg.)"),
                              ("em_integration", "Emerg.\\ integ."), ("em_utility", "Emerg.\\ util.")]),
]


def _logo(model_key: str) -> str:
    """Reuse \provlogo, the same macro the main leaderboard emits, so both tables render logos
    identically. It is \providecommand'd in each generated file, so either can be included alone."""
    slug = LOGO_SLUG.get(_provider(model_key) or "")
    if slug and (LOGO_DIR / f"{slug}.pdf").exists():
        return rf"\provlogo{{{slug}.pdf}}"
    return ""


def _name(k):
    return _logo(k) + DISPLAY.get(k, k.replace("_", "/"))


def _pct(x):
    return f"{100 * x:.1f}" if isinstance(x, (int, float)) else "n/a"


def render(c: dict) -> str:
    pm = c["per_model"]
    order = c["ranking"]
    L = ["% Auto-generated by make_appendix_tables.py -- do not edit by hand.",
         r"\providecommand{\provlogo}[1]{\raisebox{-0.15ex}{\includegraphics[height=0.85em]"
         r"{media/logos/#1}}\,}"]

    # (1) full leaderboard: overall + per-task composite, all models.
    L += [r"\begin{table}[t]", r"\centering", r"\small",
          r"\caption{\textbf{Full leaderboard.} Every model by the per-dimension "
          r"composite, as a \% of the maximum (stationary); the top rows appear in \Cref{tab:leaderboard}.}",
          r"\label{tab:leaderboard_full}", FIT_OPEN, r"\begin{tabular}{rlcccc}", r"\toprule",
          r"Rank & Model & \textbf{Overall} & Association & Analogy & Blending \\", r"\midrule"]
    for i, m in enumerate(order, 1):
        pt = pm[m]["per_task"]
        L.append(f"{i} & {_name(m)} & {_pct(pm[m]['overall'] / 100)} & "
                 f"{_pct(pt['association'] / 100)} & {_pct(pt['analogy'] / 100)} & "
                 f"{_pct(pt['blending'] / 100)} \\\\")
    L += [r"\bottomrule", r"\end{tabular}", FIT_CLOSE, r"\end{table}", ""]

    # (2) per-task dimension tables, ordered by that task's composite.
    for label, key, dims in TASKS:
        rank = sorted(order, key=lambda m: pm[m]["per_task"].get(key) or -1, reverse=True)
        cols = "l" + "c" * (len(dims) + 1)
        head = " & ".join(h for _, h in dims)
        L += [r"\begin{table}[t]", r"\centering", r"\small",
              rf"\caption{{\textbf{{{label}: full per-dimension scores.}} Every model's "
              rf"score on each dimension, as a \% of the maximum, ordered by the task composite.}}",
              rf"\label{{tab:full_{key}}}", FIT_OPEN, rf"\begin{{tabular}}{{{cols}}}", r"\toprule",
              rf"Model & \textbf{{Composite}} & {head} \\", r"\midrule"]
        for m in rank:
            raw = pm[m]["raw"][key]
            vals = " & ".join(_pct(raw.get(d)) for d, _ in dims)
            L.append(f"{_name(m)} & {_pct(pm[m]['per_task'][key] / 100)} & {vals} \\\\")
        L += [r"\bottomrule", r"\end{tabular}", FIT_CLOSE, r"\end{table}", ""]
    return "\n".join(L) + "\n"


def main(composite_path, out_path):
    c = json.loads(Path(composite_path).read_text())
    Path(out_path).write_text(render(c))
    print(f"Wrote {out_path} ({len(c['ranking'])} models; 1 leaderboard + 3 per-task tables)")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("composite_path")
    ap.add_argument("out_path")
    a = ap.parse_args()
    main(a.composite_path, a.out_path)
