"""Render per-task full-result tables (every model, every scoring dimension) for the appendix.

For each task (association / analogy / blending) emits a ``table[t]`` with one row per model and a
column per scoring dimension --- utility, surprise, originality, and (analogy/blending) emergent
creativity --- using the raw per-dimension means from ``scores_summary.json``. Models are ordered by
that task's utility-gated z-composite (from ``composite.json``) so the ordering matches the leaderboard.

    python src/kg_creat/scripts/make_appendix_tables.py \\
        data/kg_creat/kombine_v1/scores papers/kg_creat-iclr/media/03_per_task_full.tex
"""

import argparse
import json
from pathlib import Path

DISPLAY = {
    "openai_gpt-5": "gpt-5", "openai_gpt-4o-mini": "gpt-4o-mini",
    "anthropic_claude-sonnet-4-5": "claude-sonnet-4.5", "google_gemini-2-5-flash": "gemini-2.5-flash",
    "qwen_qwen-2-5-72b-instruct": "qwen-2.5-72b", "meta-llama_llama-3-3-70b-instruct": "llama-3.3-70b",
    "meta-llama_llama-3-1-8b-instruct": "llama-3.1-8b",
}
# (task label, internal mode key, has emergent column)
TASKS = [("Association", "baseline", False), ("Analogy", "analogy", True), ("Blending", "blending", True)]
DIM = {"utility": "sat_rate", "surprise": "R_emit", "originality": "originality_mean",
       "emergent": "emergent_mean"}


def _name(k):
    return DISPLAY.get(k, k.replace("_", "/"))


def _fmt(x):
    return f"{x:.2f}" if isinstance(x, (int, float)) else "n/a"


def render(summary: dict, composite: dict) -> str:
    pm = composite["per_model"]
    lines = ["% Auto-generated by make_appendix_tables.py -- do not edit by hand."]
    for label, mode, has_em in TASKS:
        tkey = "association" if mode == "baseline" else mode
        models = sorted((m for m in summary if mode in summary[m]["per_mode"]),
                        key=lambda m: (pm.get(m, {}).get("per_task", {}).get(tkey) or -1e9), reverse=True)
        cols = ["utility", "surprise", "originality"] + (["emergent"] if has_em else [])
        head = "Model & " + " & ".join(c.capitalize() for c in cols) + " \\\\"
        lines += [
            "\\begin{table}[t]", "\\centering",
            f"\\caption{{\\textbf{{{label}: full per-model scores.}} Raw per-dimension means for every "
            f"model: utility (factual/valid rate), surprise (mean $d^\\phi_{{\\cos}}$), originality "
            f"(mean $\\hat p_a(e)^{{-1}}$)" + (", and emergent creativity (mean verified inferences)"
            if has_em else "") + ". Ordered by the task $z$-composite (\\Cref{tab:leaderboard}).}",
            f"\\label{{tab:full_{tkey}}}", "\\begin{tabular}{l" + "c" * len(cols) + "}",
            "\\toprule", head, "\\midrule",
        ]
        for m in models:
            d = summary[m]["per_mode"][mode]
            vals = " & ".join(_fmt(d.get(DIM[c])) for c in cols)
            lines.append(f"{_name(m)} & {vals} \\\\")
        lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    return "\n".join(lines)


def main(scores_dir, out_path):
    scores_dir = Path(scores_dir)
    summary = json.loads((scores_dir / "scores_summary.json").read_text())
    composite = json.loads((scores_dir / "composite.json").read_text())
    Path(out_path).write_text(render(summary, composite))
    print(f"Wrote {out_path} ({len(summary)} models x 3 tasks)")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("scores_dir")
    ap.add_argument("out_path")
    main(*vars(ap.parse_args()).values())
