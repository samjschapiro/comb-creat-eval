"""Build the move-examples table: for each reasoning STEP (the moves in the forest plot), a
verbatim excerpt pulled from a real trace, rotating through the models so every model appears
as the source of an example and every step is illustrated. Emits a LaTeX table for the appendix
(directly above the 3-column move-position forest plot).

Usage:
    PYTHONPATH=. .venv/bin/python src/plot_twist/scripts/make_move_examples.py
"""

from __future__ import annotations

import glob
import json
import re
from collections import defaultdict
from pathlib import Path

from src.plot_twist.scripts.make_move_positions import MOVES, STORIES

OUT = Path("papers/pt2cb-iclr-2027/tables/tab_move_examples.tex")
PHASE = {"S": "batlowOrange", "C": "batlowBlue", "N": "batlowGreen"}  # colours defined in main.tex
PHASE_NAME = {"S": "diverge", "C": "converge", "N": "frame"}


def _esc(s: str) -> str:
    for a, b in [("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"),
                 ("#", r"\#"), ("_", r"\_"), ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"),
                 ("^", r"\textasciicircum{}"), ('"', "''")]:
        s = s.replace(a, b)
    return s


def _excerpt(trace: str, start: int, end: int, width: int = 95) -> str:
    """A readable window around [start,end), trimmed to word boundaries, whitespace-collapsed."""
    lo = max(0, start - max(0, (width - (end - start)) // 2))
    hi = min(len(trace), lo + width)
    seg = re.sub(r"[*`#]+", "", trace[lo:hi])     # strip markdown bold/headers/code noise
    seg = re.sub(r"\s+", " ", seg).strip()
    if lo > 0:
        seg = seg.split(" ", 1)[-1]          # drop a partial leading word
    if hi < len(trace):
        seg = seg.rsplit(" ", 1)[0]          # drop a partial trailing word
    pre = "\\ldots " if lo > 0 else ""
    post = " \\ldots" if hi < len(trace) else ""
    return pre + _esc(seg) + post


def main():
    traces = [json.load(open(f)) for f in glob.glob(STORIES) if json.load(open(f)).get("reasoning_trace")]
    by_model = defaultdict(list)
    for r in traces:
        if (r.get("reasoning_trace") or "").strip():
            by_model[r["model"]].append(r)
    models = sorted(by_model)

    rows = []
    for i, (label, side, pat) in enumerate(MOVES):
        rx = re.compile(pat, re.I)
        order = models[i % len(models):] + models[:i % len(models)]  # prefer model i, then others
        chosen = None
        for m in order:
            for r in by_model[m]:
                mt = rx.search(r["reasoning_trace"])
                if mt:
                    chosen = (m, _excerpt(r["reasoning_trace"], mt.start(), mt.end()))
                    break
            if chosen:
                break
        if chosen:
            rows.append((side, label, chosen[1], chosen[0].split("/")[-1]))

    # Emitted as a TABULAR FRAGMENT (+ \captionof) so it can be embedded directly above the
    # forest-plot figure inside one float (see sections/05_reasoning_trace_analysis.tex).
    lines = [r"% Auto-generated by make_move_examples.py -- verbatim reasoning-trace excerpts.",
             r"{\small\setlength{\tabcolsep}{5pt}\renewcommand{\arraystretch}{1.25}",
             r"\begin{tabular}{@{}llp{0.48\linewidth}l@{}}", r"\toprule",
             r"\textbf{Phase} & \textbf{Step} & \textbf{Verbatim reasoning excerpt} & \textbf{Model} \\",
             r"\midrule"]
    for side, label, exc, model in rows:
        col = PHASE[side]
        lines.append(f"\\textcolor{{{col}}}{{{PHASE_NAME[side]}}} & "
                     f"\\textcolor{{{col}}}{{{_esc(label)}}} & \\textit{{{exc}}} & \\texttt{{{_esc(model)}}} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}}",
              r"\captionof{table}{One verbatim excerpt of each reasoning \emph{step}, each drawn from "
              r"a different model's trace (every model represented). Steps are coloured by phase "
              r"(\textcolor{batlowGreen}{frame}, \textcolor{batlowOrange}{diverge / surprise}, "
              r"\textcolor{batlowBlue}{converge / coherence}); their within-trace positions, by "
              r"effort level, are below (\Cref{fig:move_positions_effort}).}",
              r"\label{tab:move_examples}", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"saved -> {OUT}  ({len(rows)} steps)")
    for side, label, exc, model in rows:
        print(f"  [{PHASE_NAME[side]:>8}] {label:<32} <{model}>  {exc[:70]}")


if __name__ == "__main__":
    main()
