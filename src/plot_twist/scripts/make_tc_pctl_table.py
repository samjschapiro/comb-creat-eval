"""Percentile leaderboard tables (booktabs) -- the tabular equivalent of the old
tc_scorecard plot, but every cell is a PERCENTILE RANK within the pool.

Emits two files into the tables/ dir:
  tab_pctl_top.tex          main body: the top-N systems per facet AND overall
                            (the scorecard's five ranked lists, as columns)
  tab_pctl_leaderboard.tex  appendix: the full per-system longtable

Percentiles match the radar figure's scale (per-facet pool percentile). Overall =
mean of the four facet percentiles. Expert humans are bolded throughout.

Usage:
    .venv/bin/python src/plot_twist/scripts/make_tc_pctl_table.py \
        data/plot_twist/tc/tc.json papers/pt2cb-iclr-2027/tables
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import numpy as np

FACETS = [("mean_surprise", "Surprise"), ("mean_coherence", "Coherence"),
          ("div", "Diversity"), ("mean_realism", "Realistic")]
TOP_N = 8


def short(src: str) -> str:
    if src == "human":
        return "Expert humans"
    name = src.split("/")[-1]
    for suf in ("-instruct", "-it"):
        if name.endswith(suf):
            name = name[: -len(suf)]
    name = re.sub(r"-a\d+b\b", "", name)        # drop active-param token (-a3b, -a4b)
    name = re.sub(r"-\d{2}-\d{2}$", "", name)   # drop -MM-DD date suffix
    name = re.sub(r"-\d{3,4}$", "", name)       # drop -NNN(N) id suffix (e.g. -0905)
    name = name.replace("terminus", "term.")
    return name.replace("_", r"\_").replace("&", r"\&")


def build(rows):
    pool = {k: np.array([d[k] for d in rows], dtype=float) for k, _ in FACETS}

    def pctrank(key, x):
        v = pool[key]
        return 100.0 * (np.sum(v < x) + 0.5 * np.sum(v == x)) / len(v)

    recs = []
    for d in rows:
        p = {k: pctrank(k, d[k]) for k, _ in FACETS}
        recs.append({"src": d["source"], "p": p, "ov": float(np.mean(list(p.values())))})
    return recs


def cell(rec, val):
    """`Model (pp)` cell; bold for the human row."""
    txt = f"{short(rec['src'])}~({val:.0f})"
    return rf"\textbf{{{txt}}}" if rec["src"] == "human" else txt


def top_table(recs):
    # one ranked column per facet, plus Overall
    cols = [("Overall", lambda r: r["ov"])] + [(lab, (lambda k: lambda r: r["p"][k])(key))
                                               for key, lab in FACETS]
    ranked = [sorted(recs, key=lambda r: -getf(r)) for _, getf in cols]  # full lists, sliced below

    lines = [
        "% Auto-generated by make_tc_pctl_table.py -- do not edit by hand.",
        r"% Fragment (no float wrapper): embedded at the top of a figure float so this table",
        r"% always renders directly above that figure. Caption via \captionof (needs the caption pkg).",
        r"\captionof{table}{\textbf{Top systems by transformational-creativity percentile.} The "
        rf"{TOP_N} highest-scoring systems on \textit{{Overall}} (mean of the four facet percentiles) "
        r"and on each facet; each entry gives the system and its percentile rank within the pool "
        r"(higher is better). Expert humans (bold) top the \textit{Overall} ranking and the "
        r"\textit{Realistic} facet, and are the only system strong on all four at once. The two rows "
        r"below the rule are ranks $9$ and $14$, at which expert humans enter the \textit{Diversity} "
        r"and \textit{Surprise} columns (their best two facets outside the top eight).}",
        r"\label{tab:pctl_top}",
        r"{\footnotesize",
        r"\setlength{\tabcolsep}{5pt}",
        r"\resizebox{\textwidth}{!}{%",
        r"\begin{tabular}{r" + "l" * len(cols) + "}",
        r"\toprule",
        "Rank & " + " & ".join(rf"\textbf{{{lab}}}" for lab, _ in cols) + r" \\",
        r"\midrule",
    ]
    def row(rank):
        idx = rank - 1
        cells = [cell(ranked[c][idx], getf(ranked[c][idx])) for c, (_, getf) in enumerate(cols)]
        return f"{rank} & " + " & ".join(cells) + r" \\"

    for i in range(TOP_N):
        lines.append(row(i + 1))

    # Two fully-populated extra rows at the ranks where expert humans enter the Diversity
    # and Surprise columns (their best two facets outside the top eight), in ascending order.
    human = next(r for r in recs if r["src"] == "human")

    def frank(key):
        return 1 + sum(1 for r in recs if r["p"][key] > human["p"][key])

    lines.append(r"\midrule")
    for rank in sorted({frank("div"), frank("mean_surprise")}):
        lines.append(row(rank))
    lines += [r"\bottomrule", r"\end{tabular}}", r"}"]
    return "\n".join(lines) + "\n"


def full_table(recs):
    recs = sorted(recs, key=lambda r: -r["ov"])
    lines = [
        "% Auto-generated by make_tc_pctl_table.py -- do not edit by hand.",
        r"\begin{longtable}{rl ccccc}",
        r"\caption{\textbf{Transformational-creativity leaderboard, in percentiles.} Each cell is "
        r"the system's \emph{percentile rank} within the pool on that facet (higher is better); "
        r"\textit{Overall} is the mean of the four facet percentiles. Sorted by \textit{Overall}; "
        r"expert humans in bold. Tabular form of the radar profiles "
        r"(Fig.~\ref{fig:scorecard}).}\label{tab:pctl_leaderboard}\\",
        r"\toprule",
        r"\# & System & Surp. & Coh. & Div. & Real. & Overall \\",
        r"\midrule \endfirsthead",
        r"\multicolumn{7}{l}{\footnotesize\itshape Table~\ref{tab:pctl_leaderboard} continued} \\",
        r"\toprule",
        r"\# & System & Surp. & Coh. & Div. & Real. & Overall \\",
        r"\midrule \endhead",
        r"\midrule \multicolumn{7}{r}{\footnotesize\itshape continued on next page} \\ \endfoot",
        r"\bottomrule \endlastfoot",
    ]
    for i, r in enumerate(recs, start=1):
        vals = [f"{r['p'][k]:.0f}" for k, _ in FACETS] + [f"{r['ov']:.0f}"]
        name = short(r["src"])
        if r["src"] == "human":
            name = rf"\textbf{{{name}}}"
            vals = [rf"\textbf{{{v}}}" for v in vals]
        lines.append(f"{i} & {name} & " + " & ".join(vals) + r" \\")
    lines.append(r"\end{longtable}")
    return "\n".join(lines) + "\n"


def main(tc_json: str, tables_dir: str) -> None:
    rows = json.loads(Path(tc_json).read_text())
    recs = build(rows)
    out = Path(tables_dir)
    out.mkdir(parents=True, exist_ok=True)
    (out / "tab_pctl_top.tex").write_text(top_table(recs))
    print(f"saved: {out/'tab_pctl_top.tex'} (top {TOP_N} per facet + Overall)")


if __name__ == "__main__":
    tc = sys.argv[1] if len(sys.argv) > 1 else "data/plot_twist/tc/tc.json"
    od = sys.argv[2] if len(sys.argv) > 2 else "papers/pt2cb-iclr-2027/tables"
    main(tc, od)
