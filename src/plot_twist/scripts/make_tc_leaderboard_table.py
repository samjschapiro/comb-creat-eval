"""Full appendix leaderboard: every system ranked by the (realism-gated) headline
composite, with its RAW facet values -- surprise, coherence, realism (1-5), and
diversity (mean pairwise reveal distance). Complements the percentile table
(make_tc_pctl_table.py) by showing the underlying values, not ranks.

Usage:
    .venv/bin/python src/plot_twist/scripts/make_tc_leaderboard_table.py \
        data/plot_twist/tc/tc.json papers/pt2cb-iclr-2027/tables
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path


def short(src: str) -> str:
    if src == "human":
        return "Expert humans"
    name = src.split("/")[-1]
    for suf in ("-instruct", "-it"):
        if name.endswith(suf):
            name = name[: -len(suf)]
    name = re.sub(r"-a\d+b\b", "", name)        # drop active-param token (-a3b, -a4b)
    name = re.sub(r"-\d{2}-\d{2}$", "", name)   # drop -MM-DD date suffix
    name = re.sub(r"-\d{3,4}$", "", name)       # drop -NNN(N) id suffix (e.g. -0905)
    name = name.replace("terminus", "term.")
    return name.replace("_", r"\_").replace("&", r"\&")


def build(tc_json: str, tables_dir: str) -> None:
    rows = json.loads(Path(tc_json).read_text())
    rows = sorted(rows, key=lambda d: -d["overall_eq"])

    lines = [
        "% Auto-generated by make_tc_leaderboard_table.py -- do not edit by hand.",
        r"\begin{longtable}{rl ccc c c}",
        r"\caption{\textbf{Full transformational-creativity leaderboard (raw facet values).} "
        r"Every evaluated system, ranked by the realism-gated headline composite "
        r"(\textit{Overall}, equal-weight $z$ of gated surprise, gated coherence, and "
        r"diversity). \textit{Surprise}, \textit{Coherence}, and \textit{Realism} are mean "
        r"rubric scores ($1$--$5$); \textit{Diversity} is the mean pairwise distance between "
        r"reveal embeddings. Surprise/coherence enter \textit{Overall} only for fully "
        r"realistic stories, so a high raw surprise paired with low realism need not lift "
        r"the composite. Expert humans in bold.}\label{tab:tc_leaderboard}\\",
        r"\toprule",
        r"\# & System & Surprise & Coherence & Realism & Diversity & Overall \\",
        r"\midrule \endfirsthead",
        r"\multicolumn{7}{l}{\footnotesize\itshape Table~\ref{tab:tc_leaderboard} continued} \\",
        r"\toprule",
        r"\# & System & Surprise & Coherence & Realism & Diversity & Overall \\",
        r"\midrule \endhead",
        r"\midrule \multicolumn{7}{r}{\footnotesize\itshape continued on next page} \\ \endfoot",
        r"\bottomrule \endlastfoot",
    ]
    for i, d in enumerate(rows, start=1):
        vals = [f"{d['mean_surprise']:.2f}", f"{d['mean_coherence']:.2f}",
                f"{d['mean_realism']:.2f}", f"{d['div']:.3f}", f"{d['overall_eq']:+.2f}"]
        name = short(d["source"])
        if d["source"] == "human":
            name = rf"\textbf{{{name}}}"
            vals = [rf"\textbf{{{v}}}" for v in vals]
        lines.append(f"{i} & {name} & " + " & ".join(vals) + r" \\")
    lines.append(r"\end{longtable}")

    out = Path(tables_dir)
    out.mkdir(parents=True, exist_ok=True)
    (out / "tab_tc_leaderboard.tex").write_text("\n".join(lines) + "\n")
    print(f"saved: {out/'tab_tc_leaderboard.tex'}  ({len(rows)} systems)")


if __name__ == "__main__":
    tc = sys.argv[1] if len(sys.argv) > 1 else "data/plot_twist/tc/tc.json"
    od = sys.argv[2] if len(sys.argv) > 2 else "papers/pt2cb-iclr-2027/tables"
    build(tc, od)
